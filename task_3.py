world_champions = {
    2002: 'Бразилия',
    2006: 'Италия',
    2010: 'Испания',
    2014: 'Германия',
    2018: 'Франция'
}


# Добавь в словарь 2022 год. В 2022 году чемпионом стала Аргентина.
world_champions[2022] = 'Аргентина'


# Выведи на экран всех чемпионов в формате год - страна.
for key, value in world_champions.items():
    print(f'{key} - {value}')

# Проверь, выигрывала ли Италия в 21 веке. 
# Есть переменная country со значением Италия. Проверь, содержится ли она в словаре. 
# Если да, выведи надпись Италия cтановилась чемпионом мира по футболу в 21 веке!. А если страна отсутствует среди значений словаря, выведи на экран Италия не выигрывала чемпионат мира по футболу в 21 веке.

country = 'Италия'

if country in world_champions.values():
    print(f'Италия cтановилась чемпионом мира по футболу в 21 веке!')
    
else:
    print(f'Италия не выигрывала чемпионат мира по футболу в 21 веке.')
    

